"""Put an 8x13 image on the Uno Q matrix: compile it into `unoq_app/` and start that App over adb.

The Uno Q runs Debian + arduino-app-cli; it is reached over USB with adb (the rig will use the
same transport). The image is compiled into the sketch, so it shows from boot when the App is
the board's default App, with no Linux-side process involved.
"""

from __future__ import annotations

import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np

from .grid import COLS, ROWS, to_ascii

APP_NAME = "farm-matrix-image"
APP_SRC = Path(__file__).resolve().parents[2] / "unoq_app"
REMOTE_APP = f"/home/arduino/ArduinoApps/{APP_NAME}"


def frame_header(grid: np.ndarray) -> str:
    """C header with the grid as 0/1 bytes, row-major (what `Arduino_LED_Matrix::draw` reads)."""
    lines = ["// Generated by `farm-verifier show`; do not edit.", "#pragma once", "#include <stdint.h>", ""]
    lines += [f"// {row}" for row in to_ascii(grid)]
    lines.append(f"static uint8_t FARM_FRAME[{ROWS * COLS}] = {{")
    lines += ["  " + ", ".join(str(int(v)) for v in row) + "," for row in grid]
    lines.append("};")
    return "\n".join(lines) + "\n"


def _run(args: list[str], timeout: float) -> str:
    proc = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    out = (proc.stdout + proc.stderr).strip()
    if proc.returncode != 0:
        raise RuntimeError(f"{' '.join(args)} failed ({proc.returncode}):\n{out}")
    return out


def show(grid: np.ndarray, serial: str | None = None, make_default: bool = True) -> str:
    """Build the App with `grid`, push it, start it, and (by default) make it the boot App."""
    adb = ["adb"] + (["-s", serial] if serial else [])
    # Stop before touching files: the CLI tracks the running container via the App's .cache/,
    # so the App must stop while that state exists, and .cache/ must survive the update.
    # (`start`/`restart` refuse while running; `stop` on a stopped App is harmless.)
    # Only one App runs at a time (`start` fails with 'App "X" Is Running'), so stop whatever is running, then ours.
    listing = subprocess.run(adb + ["shell", "arduino-app-cli app list"], capture_output=True, text=True, timeout=60).stdout
    for line in listing.splitlines():
        parts = line.split()
        if parts and parts[0].startswith("user:") and "running" in parts:
            subprocess.run(adb + ["shell", f"arduino-app-cli app stop /home/arduino/ArduinoApps/{parts[0][5:]}"],
                           capture_output=True, timeout=120)
    subprocess.run(adb + ["shell", f"arduino-app-cli app stop {REMOTE_APP}"], capture_output=True, timeout=120)
    with tempfile.TemporaryDirectory() as tmp:
        app = Path(tmp) / APP_NAME
        shutil.copytree(APP_SRC, app)
        (app / "sketch" / "frame.h").write_text(frame_header(grid))
        _run(adb + ["shell", f"mkdir -p {REMOTE_APP} && rm -rf {REMOTE_APP}/sketch {REMOTE_APP}/python {REMOTE_APP}/app.yaml"], 30)
        _run(adb + ["push", f"{app}/.", REMOTE_APP], 60)
    log = _run(adb + ["shell", f"arduino-app-cli app start {REMOTE_APP}"], 300)
    if make_default:
        log += "\n" + _run(adb + ["shell", f"arduino-app-cli properties set default {REMOTE_APP}"], 30)
    return log
